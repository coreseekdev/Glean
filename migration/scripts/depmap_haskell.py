#!/usr/bin/env python3
"""Deterministic dependency mapper for Glean's Haskell sources (stdlib only).

Adapts the kit's dependency-map contract (prompts/01-dependency-map.md) to
Haskell:
  - module names come from `module X.Y.Z where` headers (never guessed from
    paths — hs-source-dirs vary per cabal stanza)
  - imports are parsed line-based: `import [qualified] M.N [as X] [hiding|(...)]`
    — the codebase's imports are single-line; continuation lines add no edge
  - in-repo edges only: cabal/third-party/generated modules are neither edges
    nor misses
  - emits edges.tsv, order.txt (SCC-condensed topological batches, deps
    first), cycles.txt (file SCCs > 1)

Excluded from the node set:
  - build/VCS/tooling dirs: .git .github .build dist-newstyle migration ...
  - not translated (DECISIONS.md): glean/test/**, **/tests/**, glean/demo/**,
    glean/bench/** (re-expressed as judge cases / parity tests, not ported)
  - generated outputs (regenerated by gen-schema / thrift codegen):
    glean/schema/hs/**, **/gen-hs2/**

Usage:
  python3 depmap_haskell.py --root path/to/Glean --out path/to/migration/depmap

Determinism: sorted walks, sorted edges, sorted SCCs. Byte-identical output
on repeated runs over an unchanged tree.
"""

import argparse
import re
import sys
from pathlib import Path

SKIP_DIR_PARTS = {
    ".git", ".github", ".build", "dist-newstyle", "dist", ".stack-work",
    "migration", "__pycache__",
    # not translated (DECISIONS.md): re-expressed as judge cases / parity tests
    "test", "tests", "Test", "demo", "bench",
    # generated thrift output dirs
    "gen-hs2",
}

GENERATED_PREFIXES = ("glean/schema/hs/",)

MODULE_RE = re.compile(r"^module\s+([A-Z][A-Za-z0-9_.']*)")
IMPORT_RE = re.compile(r"^import\s+(?:qualified\s+)?([A-Z][A-Za-z0-9_.']*)")


def find_hs_files(root: Path):
    out = []
    hs_files = sorted(root.rglob("*.hs")) + sorted(root.rglob("*.hsc"))
    for p in hs_files:
        rel = p.relative_to(root)
        if any(part in SKIP_DIR_PARTS for part in rel.parts):
            continue
        if rel.as_posix().startswith(GENERATED_PREFIXES):
            continue
        # a file without a module header (e.g. glean/if/glean_include.hs, a
        # CPP include fragment) is not a Haskell translation unit
        if module_of(p) is None:
            continue
        out.append(p)
    return out


def module_of(path: Path):
    try:
        with path.open(encoding="utf-8", errors="replace") as f:
            for line in f:
                m = MODULE_RE.match(line)
                if m:
                    return m.group(1)
    except OSError:
        pass
    return None


def imports_of(path: Path):
    mods = set()
    try:
        with path.open(encoding="utf-8", errors="replace") as f:
            for line in f:
                m = IMPORT_RE.match(line)
                if m:
                    mods.add(m.group(1))
    except OSError:
        pass
    return mods


def strongly_connected(nodes, edges):
    """Tarjan, iterative, deterministic. nodes: sorted list; edges: node -> sorted succs."""
    index, low = {}, {}
    onstack, stack = set(), []
    sccs = []
    counter = [0]
    for start in nodes:
        if start in index:
            continue
        work = [(start, 0)]
        while work:
            node, ei = work.pop()
            succs = edges.get(node, [])
            if ei == 0:
                index[node] = low[node] = counter[0]
                counter[0] += 1
                stack.append(node)
                onstack.add(node)
            else:
                # returning from succs[ei-1]: fold the child's low-link up,
                # but only if it is still on the stack (a tree child or a
                # back edge). Successors in finished SCCs are cross edges —
                # folding their low would corrupt this node's low-link.
                prev = succs[ei - 1]
                if prev in onstack:
                    low[node] = min(low[node], low[prev])
            if ei < len(succs):
                work.append((node, ei + 1))
                nxt = succs[ei]
                if nxt not in index:
                    work.append((nxt, 0))
                elif nxt in onstack:
                    low[node] = min(low[node], index[nxt])
            else:
                if low[node] == index[node]:
                    comp = []
                    while True:
                        w = stack.pop()
                        onstack.discard(w)
                        comp.append(w)
                        if w == node:
                            break
                    sccs.append(sorted(comp))
    return sccs


# Crate partition (rulebook §4): longest-prefix match on the repo-relative
# path. `lang/<x>/` is special: crate = glean-indexer-<x>.
CRATE_PREFIXES = [
    # shared thrift-type wrappers (fb303/ServiceData) used by core, indexers,
    # server alike — lowest shared layer
    ("glean/github/Facebook/", "glean-fb303"),
    ("glean/github/ServiceData/", "glean-fb303"),
    ("glean/angle/", "glean-angle"),
    ("glean/hs/", "glean-core"),
    ("glean/typed/", "glean-typed"),
    ("glean/bytecode/", "glean-bytecode"),
    ("glean/schema/", "glean-schema"),
    ("glean/db/", "glean-db"),
    ("glean/backend-local/", "glean-db"),
    ("glean/backend-api/", "glean-db"),
    ("glean/haxl/", "glean-db"),           # client datasource lives with backend
    ("glean/write/", "glean-client"),
    ("glean/client/", "glean-client"),
    ("glean/glass/", "glean-glass"),
    ("glean/lsp/", "glean-lsp"),
    ("glean/shell/", "glean-cli"),
    ("glean/tools/", "glean-cli"),
    ("glean/storage/", "glean-storage"),
    ("glean/rocksdb/", "glean-storage"),
    ("glean/lmdb/", "glean-storage"),
    ("glean/lmdb-clib/", "glean-storage"),
    ("glean/interprocess/", "glean-storage"),
    # the composition root (imports every indexer; only binaries import it)
    ("glean/index/list/", "glean-registry"),
    ("glean/index/", "glean-indexer-api"),  # Indexer record, External driver
    # bootstrap helpers: leaf dependencies of binaries/tests in every layer
    # (MUST precede the general github/Glean rule — first match wins)
    ("glean/github/Glean/Init.hsc", "glean-util"),
    ("glean/github/TestRunner.hs", "glean-util"),
    # shared github LIBRARY bits used by db (DefaultConfigs, AclKnobs, ...)
    ("glean/github/Glean/", "glean-db"),
    # client-level helper library (Derive, Init, SimpleAsync, Util/*)
    ("glean/lib/", "glean-client"),
    ("glean/github/", "glean-server"),
    ("glean/server/", "glean-server"),
    ("glean/if/", "glean-server"),
    ("glean/lib/", "glean-util"),
    ("glean/util/", "glean-util"),
]


def crate_of(rel_path: str) -> str:
    for prefix, crate in CRATE_PREFIXES:
        if rel_path.startswith(prefix):
            return crate
    if rel_path.startswith("glean/lang/"):
        parts = rel_path.split("/")
        if len(parts) > 2:
            return f"glean-indexer-{parts[2]}"
        return "glean-indexer"
    return "glean-unassigned"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--crates", action="store_true",
                    help="also condense the graph to crate boundaries and "
                         "check for crate-level cycles (writes crates.txt)")
    args = ap.parse_args()
    root = args.root.resolve()
    out = args.out
    out.mkdir(parents=True, exist_ok=True)

    files = find_hs_files(root)
    mod2file = {}
    for p in files:
        m = module_of(p)
        if m:
            mod2file.setdefault(m, p)

    nodes = sorted(p.relative_to(root).as_posix() for p in files)
    edges = {}
    for p in files:
        rel = p.relative_to(root).as_posix()
        deps = set()
        for m in imports_of(p):
            t = mod2file.get(m)
            if t and t != p:
                deps.add(t.relative_to(root).as_posix())
        edges[rel] = sorted(deps)

    with (out / "edges.tsv").open("w") as f:
        for src in nodes:
            for d in edges[src]:
                f.write(f"{src}\t{d}\n")

    sccs = strongly_connected(nodes, edges)
    comp_of = {n: i for i, c in enumerate(sccs) for n in c}
    cdeps = {i: set() for i in range(len(sccs))}
    for src, dsts in edges.items():
        for d in dsts:
            a, b = comp_of[src], comp_of[d]
            if a != b:
                cdeps[a].add(b)

    batches, done, remaining = [], set(), set(range(len(sccs)))
    while remaining:
        ready = [i for i in sorted(remaining) if cdeps[i] <= done]
        if not ready:
            raise RuntimeError("cycle in condensed graph")
        take = ready[0]
        batches.append(sorted(sccs[take]))
        done.add(take)
        remaining.discard(take)

    with (out / "order.txt").open("w") as f:
        for b in batches:
            f.write("\t".join(b) + "\n")

    multi = sorted((c for c in sccs if len(c) > 1),
                   key=lambda c: (-len(c), c[0]))
    with (out / "cycles.txt").open("w") as f:
        for c in multi:
            f.write(" ".join(c) + "\n")
        f.write(f"# file-level SCCs > 1: {len(multi)} of {len(sccs)} SCCs\n")

    n_edges = sum(len(v) for v in edges.values())
    print(f"files={len(files)} modules={len(mod2file)} edges={n_edges} "
          f"sccs={len(sccs)} multi_file_sccs={len(multi)}")

    if args.crates:
        crate_edges = {}
        for src, dsts in edges.items():
            a = crate_of(src)
            for d in dsts:
                b = crate_of(d)
                if a != b:
                    crate_edges.setdefault(a, set()).add(b)
        crates = sorted({crate_of(n) for n in nodes})
        csccs = strongly_connected(crates,
                                   {c: sorted(crate_edges.get(c, []))
                                    for c in crates})
        cmulti = sorted((c for c in csccs if len(c) > 1),
                        key=lambda c: (-len(c), c[0]))
        with (out / "crates.txt").open("w") as f:
            for c in sorted(crates):
                f.write(f"{c}\t{sum(1 for n in nodes if crate_of(n) == c)}\n")
            f.write("# crate-level SCCs > 1 (the compiler-enforced partition):\n")
            for c in cmulti:
                f.write(" ".join(c) + "\n")
            f.write(f"# crates={len(crates)} crate_edges="
                    f"{sum(len(v) for v in crate_edges.values())} "
                    f"crate_cycles={len(cmulti)}\n")
        print(f"crates={len(crates)} crate_cycles={len(cmulti)}")


if __name__ == "__main__":
    sys.exit(main())
