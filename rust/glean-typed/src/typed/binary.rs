// One mechanical pattern for all arities, mirroring the source's applicative
// chains `(,) <$> ... <*> ...`, `(,,) <$> ... <*> ... <*> ...`:
//   * the first TWO elements go through build.rs's free `ap` (:310). `ap`
//     needs `F: Fn(A) -> B + 'static`, so the FIRST decoder is mapped to a
//     CLOSURE-RETURNING-CLOSURE — `map(|a| move |b| (a, b))` — where `a` is
//     fresh on every run (the composed decoder re-runs element A's decoder
//     each time, so the captured `a` is never stale);
//   * each FURTHER element chains `and_then` (build.rs:274,
//     `impl Fn(A) -> Decoder<B>`) — run everything decoded so far, then run
//     the next element's decoder against the SAME env, in order.
// Element order is left-to-right in both combinators, exactly as the
// source's `<$>`/`<*>` chain sequences them.

impl<A: Type<A> + 'static, B: Type<B> + 'static> Type<(A, B)> for (A, B) {
    fn build_rts_value(&self, b: &mut Builder) {
        self.0.build_rts_value(b);
        self.1.build_rts_value(b);
    }
    fn decode_rts_value() -> Decoder<(A, B)> {
        // (,) <$> decodeRtsValue <*> decodeRtsValue (Binary.hs:246-248)
        ap(
            &A::decode_rts_value().map(|a| move |b| (a, b)),
            &B::decode_rts_value(),
        )
    }
    fn source_type() -> SourceTypeWithRefs<()> {
        tuple_schema(vec![A::source_type(), B::source_type()])
    }
}

