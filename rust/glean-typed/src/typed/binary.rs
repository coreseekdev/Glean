/// `FFI.ffiBuf buf $ RTS.glean_pop_value_* begin end` (Binary.hs:115/:123/
/// :158/:166/:178/:201/:212/:226/:236) — run one single-out-slot pop against
/// the env's shared FFIResultBuf slot, returning the one-word result.
///
/// The pop is passed as a TYPED `unsafe extern "C" fn` pointer (the dffi
/// precedent, rts.rs:806-836): an `unsafe extern "C" fn` item does NOT
/// implement `Fn`/`FnOnce`, so it cannot be handed to ffi.rs's `impl
/// FnOnce` closure parameter directly — the safe closure below performs the
/// call inside its own `unsafe` block. `begin` is passed BY VALUE (the
/// cursor CELL, `*mut *const c_void` — the C pop advances the pointee in
/// place), never dereferenced here.
fn ffi_buf<T: Copy>(
    env: &mut DecoderEnv<'_>,
    f: unsafe extern "C" fn(
        *mut *const c_void,
        *const c_void,
        *mut T,
    ) -> *const c_char,
) -> Result<T, DecodeError> {
    let begin = env.begin;
    let end = env.end;
    let buf = &mut *env.buf;
    // SAFETY: `buf` is the live shared slot borrowed from the enclosing
    // `with_ffi_result_buf` scope; `begin`/`end` are the input range
    // `decode_with_cache` installed; `ffi_buf`'s contract (ffi.rs:701-713)
    // is exactly this out-slot call and it owns the error string.
    unsafe {
        ffi::ffi_buf(buf, |slot| {
            // SAFETY: one pop against the range above, writing exactly one
            // T into `slot` before returning null on success.
            unsafe { f(begin, end, slot) }
        })
    }
    .map_err(DecodeError::from)
}

/// `FFI.invoke $ RTS.glean_pop_value_string begin end` (Binary.hs:132) —
/// the two-out-slot pop (bytes pointer + size), routed through the shared
/// FFIResultBuf's two words (`ffi::ffi_buf2`, ffi.rs:720-734). The Haskell
/// used Util.FFI.invoke's curried out-param tuple instance; the shared-slot
/// twin is the port's image of that marshalling (this file retains the
/// shared slot per the header's sanctioned-retention note — the
/// locals-plus-invoke alternative of ffi.rs:381-385 is the row-60 idiom
/// rts.rs adopted on ITS decode side, not this file's). Monomorphic: only
/// `glean_pop_value_string` has this arity.
fn invoke2(env: &mut DecoderEnv<'_>) -> Result<(*mut c_void, usize), DecodeError> {
    let begin = env.begin;
    let end = env.end;
    let buf = &mut *env.buf;
    // SAFETY: as `ffi_buf`, for both slots (the string pop writes the
    // pointer into the first word and the size into the second;
    // ffi_buf2's contract, ffi.rs:715-734, owns the error string).
    unsafe {
        ffi::ffi_buf2(buf, |p, n| {
            // SAFETY: one string pop against the range above, writing the
            // malloc'd bytes pointer through `p` and the size through `n`
            // before returning null on success.
            unsafe { sys::glean_pop_value_string(begin, end, p, n) }
        })
    }
    .map_err(DecodeError::from)
}

/// `FFI.ffiBuf buf $ RTS.glean_pop_value_bytes begin end size`
