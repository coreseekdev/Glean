/// Lists are preceded with their length (Binary.hs:172).
impl<A: Type<A> + 'static> Type<Vec<A>> for Vec<A> {
    fn build_rts_value(&self, b: &mut Builder) {
        // liftIO $ do { glean_push_value_array b (fromIntegral $ length xs);
        // mapM_ (buildRtsValue b) xs } (Binary.hs:174-176).
        // SAFETY: as the u64 arm; the length is the slice's own.
        invoke_push(|| unsafe { sys::glean_push_value_array(b.as_ptr(), self.len()) });
        for x in self {
            x.build_rts_value(b);
        }
    }
    fn decode_rts_value() -> Decoder<Vec<A>> {
        // Decoder $ \env@DecoderEnv{..} -> do
        //   size <- FFI.ffiBuf buf $ RTS.glean_pop_value_array begin end
        //   replicateM (fromIntegral size) (runDecoder decodeRtsValue env)
        // (Binary.hs:177-179). The inner decoder is captured ONCE and run
        // `size` times — the reusable-Decoder shape build.rs:227-230 cites
        // this very instance for.
        let inner = A::decode_rts_value();
        Decoder::new(move |env| {
            let size: usize = ffi_buf(env, sys::glean_pop_value_array)?;
            // RULE §2 (numeric-conversions): the source's `replicateM
            // (fromIntegral size)` converts the CSize to Int, so a size >=
            // 2^63 wraps NEGATIVE and replicates ZERO times — an EMPTY
            // list, with no element decode attempted and the cursor
            // untouched. Reproduced bug-for-bug with the explicit `as i64`
            // (the same reasoning rts.rs:1073-1086 records for the
            // identical construct in decode_value). The Vec is also built
            // from empty rather than `with_capacity(size)` — the size is
            // not pre-validated, and a huge count must not become a huge
            // allocation (rts.rs:1042-1044).
            let count = size as i64;
            let mut out = Vec::new();
            if count > 0 {
                for _ in 0..count {
                    out.push(inner.run_decoder(env)?);
                }
            }
            Ok(out)
        })
    }
    fn source_type() -> SourceTypeWithRefs<()> {
        Type_::ArrayTy(Box::new(A::source_type()))
    }
}

/// 'Maybe' is alias pattern for sum of () | 'a' (in this order)
/// (Binary.hs:183).
impl<A: Type<A> + 'static> Type<Option<A>> for Option<A> {
    fn build_rts_value(&self, b: &mut Builder) {
        // buildRtsValue b Nothing = buildRtsSelector b 0
        // buildRtsValue b (Just x) = do { buildRtsSelector b 1;
        //   buildRtsValue b x }  (Binary.hs:185-188)
        match self {
            None => build_rts_selector(b, 0),
            Some(x) => {
                build_rts_selector(b, 1);
                x.build_rts_value(b);
            }
        }
    }
    fn decode_rts_value() -> Decoder<Option<A>> {
        // sumD (Decoder $ \_ -> decodeFail "maybe selector out of range")
        //   [pure Nothing, Just <$> decodeRtsValue]  (Binary.hs:189-191)
        //
        // `pure Nothing`: written as a direct Decoder construction rather
        // than `Decoder::pure(None)` — build.rs's `pure` carries an
        // `A: Clone` bound (build.rs:286-291) that the source's instance
        // does not have (Applicative.pure needs nothing but the value);
        // the closure re-runs `Ok(None)` per decode, which IS `pure`'s
        // behaviour.
        let just = A::decode_rts_value().map(Some);
        let nothing = Decoder::new(|_env: &mut DecoderEnv<'_>| Ok(None));
        sum_d(
            Decoder::new(|_env| decode_fail("maybe selector out of range")),
            vec![nothing, just],
        )
    }
    fn source_type() -> SourceTypeWithRefs<()> {
        Type_::MaybeTy(Box::new(A::source_type()))
    }
}

