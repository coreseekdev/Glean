/// `class Type a where buildRtsValue/decodeRtsValue/constantRtsValue/
/// decodeAsFact/sourceType` (Binary.hs:53-88). The Haskell typeclass is a
/// Rust trait; the two defaults (`constantRtsValue = Nothing`, Binary.hs:64,
/// and the non-predicate `decodeAsFact`, Binary.hs:84-85) carry default
/// bodies.
///
/// The `'static` bound on the trait's parameter is the unit-15 precedent
/// (build.rs:600-607): `Decoder<A>`'s closure representation is
/// `Arc<dyn for<'a> Fn(...) + 'static>`, so `Decoder<A>` is only
/// well-formed when `A: 'static` — the bound is declared once, here, and
/// every impl satisfies it.
///
/// Effect mapping: the source's `IO` open exception channel splits by
/// direction, exactly as the shipped sibling units rule it —
/// `buildRtsValue :: Builder -> a -> IO ()` returns `()` here because its
/// only failure mode is the push family's allocation guard (abort; see
/// `allocation_guard_abort`), the same disposition as rts.rs's
/// `encodeValue` (rts.rs:414-485). `decodeRtsValue :: Decoder a` keeps the
/// typed `Result` channel (`DecodeError`), as every Decoder body in
/// build.rs does.
pub trait Type<A: 'static> {
    /// `buildRtsValue :: RTS.Builder -> a -> IO ()` (Binary.hs:55). Returns
    /// `()`: an Err aborts (push-family allocation guard, see
    /// [`allocation_guard_abort`]).
    fn build_rts_value(&self, builder: &mut Builder);

    /// `decodeRtsValue :: Decoder a` (Binary.hs:58).
    fn decode_rts_value() -> Decoder<A>;

    /// `constantRtsValue = Nothing` (Binary.hs:62-64).
    fn constant_rts_value() -> Option<A> {
        None
    }

    /// `decodeAsFact nested cache _fid (Fact _ k _) = decodeWithCache
    /// nested cache decodeRtsValue k` (Binary.hs:84-85) — the default for
    /// all non-predicate types; predicate types override it with
    /// `decodeFact`.
    fn decode_as_fact(
        nested: &HashMap<i64, glean_thrift::Fact>,
        cache_ref: &mut HashMap<i64, Box<dyn std::any::Any>>,
        _fid: &IdOf<A>,
        fact: &glean_thrift::Fact,
    ) -> Result<A, DecodeError> {
        let glean_thrift::Fact { key, .. } = fact;
        decode_with_cache(nested, cache_ref, &Self::decode_rts_value(), key)
    }

    /// `sourceType :: Proxy a -> Angle.SourceType' ()` (Binary.hs:88). The
    /// Rust associated function needs no `Proxy` (the type is carried by
    /// `A`); the return type is the source's `SourceType' ()` =
    /// `SourceTypeWithRefs<()>` (angle/Types.hs:640 instantiated at `()`).
    fn source_type() -> SourceTypeWithRefs<()>;
}

/// `decodeRts :: forall m a. (MonadIO m, Type a) => ByteString -> m a`
/// (Binary.hs:94-95) — `decodeRts = decode decodeRtsValue`. build.rs's
/// `decode` (:392) takes the decoder BY VALUE and installs the fresh empty
/// cache (its `decodeWithCache IntMap.empty (newIORef IntMap.empty)
/// decoder v`, Build.hs:86-89); the `m a` result is `Result<A,
/// DecodeError>` (the `MonadIO` constraint is the open channel, pinned
/// here).
pub fn decode_rts<A: Type<A> + 'static>(v: &[u8]) -> Result<A, DecodeError> {
    decode(A::decode_rts_value(), v)
}

/// `mapD :: Type a => (a -> b) -> Decoder b` (Binary.hs:99-100) — `mapD f =
/// f <$> decodeRtsValue` (the Functor instance).
pub fn map_d<A: Type<A> + 'static, B: 'static>(f: impl Fn(A) -> B + 'static) -> Decoder<B> {
    A::decode_rts_value().map(f)
}

/// `buildRtsSelector :: RTS.Builder -> Int -> IO ()` (Binary.hs:103-104) —
/// `FFI.call . RTS.glean_push_value_selector b . fromIntegral`. The
/// source's `FFI.call` disposition on a push is the allocation-guard abort
/// (see [`allocation_guard_abort`]); `selector` is the already-widened
/// `usize` the extern takes (`fromIntegral` Int -> CSize happened at the
/// call sites).
pub fn build_rts_selector(builder: &mut Builder, selector: usize) {
    // SAFETY: `builder` is a live Builder (the &mut borrow outlives the
    // call); the push only appends to its buffer; invoke's contract covers
    // the returned pointer.
    invoke_push(|| unsafe { sys::glean_push_value_selector(builder.as_ptr(), selector) });
}

/// `thriftEnum_buildRtsValue :: forall a. ThriftEnum a => RTS.Builder -> a
/// -> IO ()` (Binary.hs:106-107) — `buildRtsSelector b $ fromThriftEnum x`.
/// `fromThriftEnum` is the FROM-direction (`a -> Int`, enum to int); the
/// ASSUMED-IMPORT extension block above documents the assumed
/// `from_thrift_enum(&self) -> i64` method. The `as usize` reproduces the
/// source's `fromIntegral` (Int -> CSize) wrap. No `Copy` bound: the
/// source's constraint is exactly `ThriftEnum a`.
pub fn thrift_enum_build_rts_value<T: ThriftEnum>(builder: &mut Builder, x: T) {
    build_rts_selector(builder, x.from_thrift_enum() as usize)
}

