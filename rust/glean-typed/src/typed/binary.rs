/// RULE §2 (error-recovery rule) + the push-family ruling: the push symbols
/// are ALLOCATION-GUARD (their bodies, ffi.cpp:680-715, contain no
/// precondition check; their only failure mode is Output growth, which
/// wrap.h returns as a message), and inventory row 61 rules "abort on OOM"
/// for that family. rts.rs's own `allocation_guard_abort` (:379) and
/// `invoke_push` (:389) are PRIVATE to rts.rs — the established pattern is
/// that each consumer file carries its own private mirror (rts.rs:377 says
/// so; subst.rs:342-343 does the same). This is that mirror: same message
/// text as rts.rs:379-382, same abort-not-panic choice so no unwinding runs
/// first. The source's `FFI.call` on a push threw `GleanFFIError` into an
/// `IO ()` that nothing in the tree catches — the abort reproduces the
/// observable outcome (the process dies), the same disposition as
/// rts.rs/builder.rs/set.rs on this same handle family.
fn allocation_guard_abort(e: FfiError) -> ! {
    eprintln!("glean: C++ builder allocation failure: {}", e);
    std::process::abort()
}

/// Run one push-symbol call through `glean_core::ffi::invoke`; an Err aborts
/// per the classification above (the rts.rs `encode_value` precedent,
/// rts.rs:420-485: every push site routes through this shape and returns
/// `()`). Not `unsafe`: each call site builds the actual extern call inside
/// its own `unsafe` block (with its SAFETY note); this helper only routes
/// the returned pointer through invoke's documented contract.
fn invoke_push(call: impl FnOnce() -> *const c_char) {
    // SAFETY: `call` runs exactly one of the push symbols, constructed by
    // the caller with a live builder handle; a non-null return follows
    // crate::ffi::invoke's contract (a wrap.h-produced NUL-terminated
    // message, read and released by invoke).
    if let Err(e) = unsafe { ffi::invoke(call) } {
        allocation_guard_abort(e);
    }
}

