use std::ffi::CString;
use std::io;
use std::os::raw::{c_char, c_int};

/// 'defaultGflags' (:59-60): tell glog to log to stderr by default;
/// command-line flags can override it.
const DEFAULT_GFLAGS: [&str; 1] = ["--logtostderr"];

/// 'follyInit :: [String] -> IO ()' (:48-55): run folly's scoped init with
/// `argv` = executable path, the default gflags, and the program's args.
///
/// Private in the source (DIVERGENCES 2).
pub fn folly_init(args: &[String]) -> io::Result<()> {
    // 'name <- Sys.getExecutablePath' (:50).
    let exe = std::env::current_exe()?;
    let exe = exe.to_string_lossy().into_owned();

    // 'let allArgs = defaultGflags <> args' (:51).
    let mut all: Vec<String> = Vec::with_capacity(1 + DEFAULT_GFLAGS.len() + args.len());
    all.push(exe);
    all.extend(DEFAULT_GFLAGS.iter().map(|s| (*s).to_string()));
    all.extend(args.iter().cloned());

    // 'withCStrings (name : allArgs) $ \argv ->' (:52): a NULL-terminated
    // vector of C strings, as withCStrings' array is.
    let cstrings: Vec<CString> = all
        .iter()
        .map(|s| CString::new(s.as_bytes()))
        .collect::<Result<_, _>>()
        .map_err(|e| io::Error::new(io::ErrorKind::InvalidInput, e))?;
    let mut argv: Vec<*mut c_char> = cstrings.iter().map(|c| c.as_ptr() as *mut c_char).collect();
    argv.push(std::ptr::null_mut());

    // 'with (fromIntegral (1 + length allArgs)) $ \pargc ->' (:53) and
    // 'with argv $ \pargv ->' (:54).
    let mut argc: c_int = (argv.len() - 1) as c_int;
    let mut argv_ptr: *mut *mut c_char = argv.as_mut_ptr();

    // SAFETY: argc/argv describe the live, NULL-terminated array above and
    // stay alive across the call; the callee is folly's documented
    // (int*, char***, bool) initialiser, which only reads them.
    unsafe { sys::folly_unsafe_unscoped_init(&mut argc, &mut argv_ptr, false) };
    Ok(())
}

