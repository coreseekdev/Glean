/// `ipv6address` (:574-632): the nine try-wrapped arms, in order. Each
/// arm is `try (do ...)`; a failure rolls back and commits nothing, so
/// the chain is a flat ordered retry (the `<?> "IPv6 address"` label is
/// diagnostic-only and is dropped).
fn ipv6address(cur: &mut Cursor) -> PResult<String> {
    let start = cur.pos;
    let arms: [fn(&mut Cursor) -> PResult<String>; 9] = [
        ipv6_arm1,
        ipv6_arm2,
        ipv6_arm3,
        ipv6_arm4,
        ipv6_arm5,
        ipv6_arm6,
        ipv6_arm7,
        ipv6_arm8,
        ipv6_arm9,
    ];
    for arm in arms {
        match try_(cur, arm) {
            Ok(v) => return Ok(v),
            Err(fail) => {
                debug_assert_eq!(fail.pos, start);
                cur.pos = start;
            }
        }
    }
    Err(Fail { pos: start })
}

