/// `parseURI` (Network/URI.hs:300-301, :360-380): `Just` iff the whole
/// string matches the absolute-URI grammar (`uri` then `eof`).
pub fn parse_uri(s: &str) -> Option<Uri> {
    let mut cur = Cursor {
        input: s.chars().collect(),
        pos: 0,
    };
    match uri(&mut cur) {
        Ok(u) if cur.pos == cur.input.len() => Some(u),
        _ => None,
    }
}

// --- parser plumbing (parsec-3.1.16.1 semantics, pinned) ------------------

struct Cursor {
    input: Vec<char>,
    pos: usize,
}

impl Cursor {
    fn peek(&self) -> Option<char> {
        self.input.get(self.pos).copied()
    }
}

/// Failure position, Parsec-style: a failure is "non-consuming" with
/// respect to a parser started at `start` iff `fail.pos == start`.
/// Cursor invariant on `Err`: `cursor.pos == fail.pos`.
#[derive(Clone, Copy, Debug)]
struct Fail {
    pos: usize,
}

type PResult<A> = Result<A, Fail>;

/// `satisfy` (Char.hs): consume one char when the predicate holds; an
/// empty failure otherwise.
fn satisfy_<F: Fn(char) -> bool>(cur: &mut Cursor, f: F) -> PResult<char> {
    match cur.peek() {
        Some(c) if f(c) => {
            cur.pos += 1;
            Ok(c)
        }
        _ => Err(Fail { pos: cur.pos }),
    }
}

/// `char c` (Char.hs).
fn char_(cur: &mut Cursor, c: char) -> PResult<char> {
    satisfy_(cur, |x| x == c)
}

/// `oneOf s` (Char.hs).
fn one_of_(cur: &mut Cursor, set: &str) -> PResult<char> {
    satisfy_(cur, |x| set.contains(x))
}

/// `string s` (Parsec.hs): failure position = start + matched prefix
/// length (see the semantics notes above; cosmetic vs Parsec).
fn string_(cur: &mut Cursor, s: &str) -> PResult<()> {
    let start = cur.pos;
    for (i, c) in s.chars().enumerate() {
        if cur.peek() == Some(c) {
            cur.pos += 1;
        } else {
            return Err(Fail { pos: start + i });
        }
    }
    Ok(())
}

/// `try p` (Prim.hs): any failure becomes an empty failure at `start`.
fn try_<A, F: FnOnce(&mut Cursor) -> PResult<A>>(cur: &mut Cursor, f: F) -> PResult<A> {
    let start = cur.pos;
    match f(cur) {
        Ok(a) => Ok(a),
        Err(_) => {
            cur.pos = start;
            Err(Fail { pos: start })
        }
    }
}

/// `p <|> q` (Prim.hs): committed choice — q runs only after p failed
/// without consuming.
fn alt<A, L, R>(cur: &mut Cursor, left: L, right: R) -> PResult<A>
where
    L: FnOnce(&mut Cursor) -> PResult<A>,
    R: FnOnce(&mut Cursor) -> PResult<A>,
{
    let start = cur.pos;
    match left(cur) {
        Ok(a) => Ok(a),
        Err(fail) => {
            debug_assert_eq!(cur.pos, fail.pos);
            if fail.pos == start {
                cur.pos = start;
                right(cur)
            } else {
                Err(fail)
            }
        }
    }
}

/// `option d p` (Prim.hs): p's empty failure becomes d.
fn opt<A, F: FnOnce(&mut Cursor) -> PResult<A>>(cur: &mut Cursor, dflt: A, f: F) -> PResult<A> {
    let start = cur.pos;
    match f(cur) {
        Ok(a) => Ok(a),
        Err(fail) => {
            if fail.pos == start {
                cur.pos = start;
                Ok(dflt)
            } else {
                Err(fail)
            }
        }
    }
}

/// `many p` (Prim.hs manyAccum): stop on the first empty failure,
/// propagate a consuming failure, panic on empty success (unreachable
/// here — every parser passed to `many` consumes on success; the panic
/// message is Parsec's, kept verbatim for fidelity).
fn many<A, F: FnMut(&mut Cursor) -> PResult<A>>(cur: &mut Cursor, mut f: F) -> PResult<Vec<A>> {
    let mut out = Vec::new();
    loop {
        let start = cur.pos;
        match f(cur) {
            Ok(a) => {
                if cur.pos == start {
                    panic!("Text.ParserCombinators.Parsec.Prim.many: combinator 'many' is applied to a parser that accepts an empty string.");
                }
                out.push(a);
            }
            Err(fail) => {
                if fail.pos == start {
                    return Ok(out);
                }
                return Err(fail);
            }
        }
    }
}

/// `many1 p`.
fn many1<A, F: FnMut(&mut Cursor) -> PResult<A>>(cur: &mut Cursor, mut f: F) -> PResult<Vec<A>> {
    let a = f(cur)?;
    let mut out = vec![a];
    out.extend(many(cur, f)?);
    Ok(out)
}

/// `count n p` (Prim.hs).
fn count_<A, F: FnMut(&mut Cursor) -> PResult<A>>(
    cur: &mut Cursor,
    n: usize,
    mut f: F,
) -> PResult<Vec<A>> {
    let mut out = Vec::with_capacity(n);
    for _ in 0..n {
        out.push(f(cur)?);
    }
    Ok(out)
}

/// `countMinMax m n p` (Network/URI.hs:920-931): the guard order is
/// significant — `m > 0` wins even when `n <= 0`.
fn count_min_max<A, F: FnMut(&mut Cursor) -> PResult<A>>(
    cur: &mut Cursor,
    m: i64,
    n: i64,
    mut f: F,
) -> PResult<Vec<A>> {
    if m > 0 {
        let a1 = f(cur)?;
        let mut rest = count_min_max(cur, m - 1, n - 1, f)?;
        let mut out = vec![a1];
        out.append(&mut rest);
        Ok(out)
    } else if n <= 0 {
        Ok(Vec::new())
    } else {
        let start = cur.pos;
        match f(cur) {
            Ok(a1) => {
                let mut rest = count_min_max(cur, 0, n - 1, f)?;
                let mut out = vec![a1];
                out.append(&mut rest);
                Ok(out)
            }
            Err(fail) if fail.pos == start => Ok(Vec::new()),
            Err(fail) => Err(fail),
        }
    }
}

/// `notFollowedBy p` (Combinator.hs): non-consuming failure iff p
/// succeeds consuming; succeeds (without consuming) when p fails OR
/// succeeds empty (Parsec's `try p` + `unexpected` + `<|> return ()`).
fn not_followed_by<A, F: FnOnce(&mut Cursor) -> PResult<A>>(
    cur: &mut Cursor,
    f: F,
) -> PResult<()> {
    let start = cur.pos;
    let r = f(cur);
    let consumed = cur.pos > start;
    cur.pos = start;
    match r {
        Ok(_) if consumed => Err(Fail { pos: start }),
        _ => Ok(()),
    }
}

