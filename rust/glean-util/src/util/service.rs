/// `escaped` (:405-406): '%' + two hex digits.
fn escaped(cur: &mut Cursor) -> PResult<String> {
    char_(cur, '%')?;
    let h1 = hex_digit_char(cur)?;
    let h2 = hex_digit_char(cur)?;
    Ok(format!("%{}{}", h1, h2))
}

/// `subDelims` (:451-452).
fn sub_delims(cur: &mut Cursor) -> PResult<String> {
    one_of_(cur, "!$&'()*+,;=").map(|c| c.to_string())
}

/// `unreservedChar` (:464-465).
fn unreserved_char(cur: &mut Cursor) -> PResult<String> {
    satisfy_(cur, is_unreserved).map(|c| c.to_string())
}

/// `uchar extras` (:787-792): unreserved / escaped / sub-delims / one of
/// `extras`.
fn uchar(cur: &mut Cursor, extras: &str) -> PResult<String> {
    alt(cur, unreserved_char, |c| {
        alt(
            c,
            escaped,
            |c| alt(c, sub_delims, |c| one_of_(c, extras).map(|x| x.to_string())),
        )
    })
}

/// `uri` (:476-491): scheme (try-wrapped), hier-part, optional query and
/// fragment.
fn uri(cur: &mut Cursor) -> PResult<Uri> {
    let us = try_(cur, uscheme)?;
    let (ua, up) = hier_part(cur)?;
    let uq = opt(cur, String::new(), |c| {
        char_(c, '?')?;
        uquery(c)
    })?;
    let uf = opt(cur, String::new(), |c| {
        char_(c, '#')?;
        ufragment(c)
    })?;
    Ok(Uri {
        scheme: us,
        authority: ua,
        path: up,
        query: uq,
        fragment: uf,
    })
}

/// `hierPart` (:493-507).
fn hier_part(cur: &mut Cursor) -> PResult<(Option<UriAuth>, String)> {
    alt(
        cur,
        |c| {
            try_(c, |c| string_(c, "//"))?;
            let ua = uauthority(c)?;
            let up = path_ab_empty(c)?;
            Ok((Some(ua), up))
        },
        |c| {
            alt(
                c,
                |c| {
                    let up = path_abs(c)?;
                    Ok((None, up))
                },
                |c| {
                    alt(
                        c,
                        |c| {
                            let up = path_root_less(c)?;
                            Ok((None, up))
                        },
                        |_c| Ok((None, String::new())),
                    )
                },
            )
        },
    )
}

