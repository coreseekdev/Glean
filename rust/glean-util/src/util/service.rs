/// Rust image of the orphan `instance IsString Service` (Service.hs:42-49).
///
/// Rust's orphan rules reject `impl From<&str> for glean_thrift::Service`
/// (foreign trait, foreign type), so the instance cannot exist; this free
/// function carries the exact heuristic — last-colon split + exact
/// `reads @Int32` of the suffix -> `HostPort`; else `parse_uri` success ->
/// `Uri`; else `Tier`. See the header block for the pinned `reads`
/// semantics the private helper below transcribes.
pub fn service_from_string(s: &str) -> Service {
    // break (==':') $ reverse s  — the LAST ':' decides host/port.
    if let Some(last_colon) = s.rfind(':') {
        let port_str = &s[last_colon + 1..];
        if let Some(port) = reads_int32_exact(port_str) {
            return Service::HostPort(HostPort {
                host: s[..last_colon].to_string(),
                port,
            });
        }
    }
    if parse_uri(s).is_some() {
        Service::Uri(s.to_string())
    } else {
        Service::Tier(s.to_string())
    }
}

