/// The layout iteration state — `data Layout s` (Code.hs:359-371) minus the
/// ST vector (the mutable label buffer is a local `Vec<u64>`; runST/
/// unsafeFreeze is a Haskell purity device, header: list-reversal note).
struct LayoutState {
    /// Current offset in the instruction stream (layoutOffset, Code.hs:
    /// 360-361).
    offset: u64,
    /// Insn stream (layoutInsns, Code.hs:363-367): reversed chunks of
    /// reversed blocks there; chunks in emission order with in-order
    /// contents here — `reverse $ concat layoutInsns` (Code.hs:419) then
    /// equals plain `concat`.
    insns: Vec<Vec<Insn>>,
    /// Blocks we want to emit, some of which might have been emitted
    /// already (layoutTodo, Code.hs:369-370) — IntSet over `fromLabel` ↦
    /// BTreeSet<i64> (IntSet.minView :414 ↦ pop_first: the numerically
    /// lowest).
    todo: BTreeSet<i64>,
}

/// Compute a flat instruction stream for a subroutine as well as a mapping
/// from labels to their offsets in that stream. Note that we don't emit
/// unreachable blocks - a block that hasn't been emitted because it's dead
/// will have the magic value of maxBound in the label->offset mapping.
///
/// This is really simple at the moment.
///
/// * Start with the entry block.
/// * If the current block ends with an unconditional jump and the block it
///   jumps to hasn't been emitted yet, continue with that block, thus
///   saving the jump.
/// * Otherwise, continue with the unemitted block with lowest label
///   number.
///
/// There is obviously ample room for improvement here. (Source doc,
/// Code.hs:373-385, verbatim.)
///
/// `layout :: CFG -> ([Insn], VP.Vector Word64)` (Code.hs:386-435).
fn layout(cfg: &CFG) -> (Vec<Insn>, Vec<u64>) {
    // mlabels <- VPM.replicate (V.length cfgBlocks) maxBound (Code.hs:388)
    let mut labels = vec![u64::MAX; cfg.cfg_blocks.len()];
    let mut st = LayoutState {
        offset: 0,
        insns: Vec::new(),
        todo: BTreeSet::new(), // IntSet.empty
    };
    // emit cfgEntry Layout{..} (Code.hs:389-394)
    emit(cfg, &mut labels, &mut st, cfg.cfg_entry);
    // The source's terminal branch freezes the label vector and returns
    // (reverse $ concat layoutInsns, labels) (Code.hs:417-419); the result
    // is a pure function of the accumulated state, so the flatten happens
    // after the outermost call instead of inside emit_next — identical
    // values (RULE §0: same data flow).
    (st.insns.concat(), labels)
}

/// Emit a specific block which must not have been emitted already
/// (source doc, Code.hs:396).
///
/// `emit :: Label -> Layout s -> ST s ([Insn], VP.Vector Word64)`
/// (Code.hs:397-409).
fn emit(cfg: &CFG, labels: &mut [u64], st: &mut LayoutState, label: Label) {
    // VPM.write layoutLabels (fromLabel label) layoutOffset — FIRST, so a
    // block ending in a Jump to ITSELF sees itself as already emitted and
    // takes the keep-jump path (no infinite fallthrough).
    labels[label.0 as usize] = st.offset;

    // case blockInsns (cfgBlocks V.! fromLabel label) of (Code.hs:401)
    // — the reversed-list head `Jump target : insns` is the block's LAST
    // instruction; the port's in-order Vec splits at the tail.
    let block = &cfg.cfg_blocks[label.0 as usize];
    match block.block_insns.split_last() {
        // Handle unconditional jumps specially (Code.hs:402)
        Some((Insn::Jump(target), rest)) => {
            // s <- stillTodo layout target (Code.hs:404)
            if labels[target.0 as usize] == u64::MAX {
                // then emit target $ addInsns insns layout (Code.hs:406)
                // — fall through into the target block: the Jump itself is
                // DROPPED (never added to the stream).
                add_insns(st, rest);
                emit(cfg, labels, st, *target);
            } else {
                // else emitNext $ addInsns (Jump target : insns) layout
                // (Code.hs:407) — keep the Jump; addInsns then re-adds
                // target to the todo set via insnLabels.
                let mut kept = rest.to_vec();
                kept.push(Insn::Jump(*target));
                add_insns(st, &kept);
                emit_next(cfg, labels, st);
            }
        }
        // insns -> emitNext $ addInsns insns layout (Code.hs:409)
        _ => {
            add_insns(st, &block.block_insns);
            emit_next(cfg, labels, st);
        }
    }
}

/// Emit the numerically lowest unemitted block (if any) (source doc,
/// Code.hs:411).
///
/// `emitNext :: Layout s -> ST s ([Insn], VP.Vector Word64)`
/// (Code.hs:412-419). The source recurses per minView step; the port
/// loops — the early `return` after `emit` mirrors the source's
/// then-branch ending the chain (emit's own recursion finishes the
/// stream).
fn emit_next(cfg: &CFG, labels: &mut [u64], st: &mut LayoutState) {
    // | Just (label, todo) <- IntSet.minView layoutTodo (Code.hs:414)
    while let Some(label) = st.todo.pop_first() {
        // s <- stillTodo layout $ Label label (Code.hs:415)
        if labels[label as usize] == u64::MAX {
            // (if s then emit (Label label) else emitNext) layout{layoutTodo
            //   = todo} (Code.hs:416)
            emit(cfg, labels, st, Label(label));
            return;
        }
        // already emitted: drop it from the todo set (popped above) and
        // take the next-lowest
    }
    // | otherwise = ... return (reverse $ concat layoutInsns, labels)
    // (Code.hs:417-419) — terminal; the flatten lives in `layout`.
}

/// Has a block already been emitted (source doc, Code.hs:421) — inlined
/// at its two call sites as the `== u64::MAX` label check:
/// `stillTodo Layout{..} label = (== maxBound) <$> VPM.read layoutLabels
/// (fromLabel label)` (Code.hs:422-424).

/// Emit instructions (Code.hs:426 heading) — `addInsns :: [Insn] ->
/// Layout s -> Layout s` (Code.hs:427-435).
fn add_insns(st: &mut LayoutState, insns: &[Insn]) {
    // layoutOffset = layoutOffset layout + sum (map insnSize insns)
    // (Code.hs:429) — Word64 `+` wraps (header DESIGN (3)).
    st.offset = st
        .offset
        .wrapping_add(insns.iter().map(insn_size).fold(0u64, u64::wrapping_add));
    // layoutTodo = foldr (IntSet.insert . fromLabel) (layoutTodo layout)
    //   (concatMap insnLabels insns) (Code.hs:430-433)
    for insn in insns {
        for l in insn_labels(insn) {
            st.todo.insert(l.0);
        }
    }
    // layoutInsns = insns : layoutInsns layout (Code.hs:434) — push in
    // emission order (the source's outer reversal collapses, header).
    st.insns.push(insns.to_vec());
}

