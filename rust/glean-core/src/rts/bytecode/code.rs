/// Control flow graph (Code.hs:318-325): `data CFG = CFG { cfgBlocks ::
/// V.Vector Block, cfgEntry :: !Label }` — private in the source, private
/// here; V.Vector ↦ Vec.
struct CFG {
    /// Basic blocks (cfgBlocks, Code.hs:320-321).
    cfg_blocks: Vec<Block>,
    /// Entry block (cfgEntry, Code.hs:323-324).
    cfg_entry: Label,
}

/// Inline blocks containing only one instruction and short-circuit labels
/// which point to blocks consisting of a single Jump.
///
/// NOTE: This will leave behind unreachable blocks. (Source doc,
/// Code.hs:327-330, verbatim — including the NOTE.)
///
/// `shortcut :: CFG -> CFG` (Code.hs:331-357).
fn shortcut(cfg: CFG) -> CFG {
    // shortcuts = cfgBlocks <&> \Block{..} -> case blockInsns of
    //   [insn] -> Just $ case insn of
    //     Jump target | Just insn' <- shortcuts V.! fromLabel target -> insn'
    //     _ -> insn
    //   _ -> Nothing                                    (Code.hs:349-353)
    //
    // The source computes this as a LAZY KNOT (shortcuts refers to itself
    // at :351): each single-instruction block's shortcut follows single-
    // Jump chains until they bottom out at a multi-instruction block (the
    // guard fails, the Jump is kept) or a non-Jump instruction (that insn
    // wins). Rust has no knot: iterate the SAME defining equation to its
    // fixpoint, Jacobi-style (every element recomputed from the previous
    // pass's values). On an acyclic block graph the fixpoint is unique —
    // each pass extends every chain by one step, so at most `n` passes —
    // and equals the knot's value.
    let n = cfg.cfg_blocks.len();
    let mut cur: Vec<Option<Insn>> = cfg
        .cfg_blocks
        .iter()
        .map(|b| {
            if b.block_insns.len() == 1 {
                Some(b.block_insns[0].clone())
            } else {
                None
            }
        })
        .collect();

    // `live` marks elements that re-evaluate in a pass (`Some(Jump t)`
    // with `cur[t] = Some(_)` — exactly the guard at Code.hs:351). A
    // pass with no live elements is the fixpoint.
    let mut converged = false;
    for _ in 0..=n {
        let mut live = false;
        let next: Vec<Option<Insn>> = (0..n)
            .map(|i| match &cur[i] {
                Some(Insn::Jump(target)) => match &cur[target.0 as usize] {
                    Some(insn) => {
                        live = true;
                        Some(insn.clone())
                    }
                    None => Some(Insn::Jump(*target)), // guard fails: keep the Jump
                },
                other => other.clone(),
            })
            .collect();
        cur = next;
        if !live {
            converged = true;
            break;
        }
    }
    if !converged {
        // BUG(port): the source's knot DIVERGES here — forcing `shortcuts`
        // on a cycle of single-Jump blocks (e.g. two blocks ending in
        // mutual `Jump`s, or a block whose only insn jumps to its own
        // label — reachable in principle by `jump L; ... L <- label; jump
        // L` shapes) raises GHC's NonTermination "<<loop>>" when
        // `V.all isNothing shortcuts` (Code.hs:333) forces the element.
        // The source marks this "FIXME: This can loop if the generated
        // code contains infinite loops" (Code.hs:348). Reproduced
        // bug-for-bug as a panic rather than a hang; a fix (cycle-proof
        // shortcutting) ships only as a flagged post-parity change (RULE
        // §2 BUG rule). Repro: build a subroutine whose block graph has a
        // cycle of single-instruction Jump blocks, call
        // generate(Optimised, ...).
        panic!("<<loop>>");
    }

    // | V.all isNothing shortcuts = cfg (Code.hs:333-334)
    if cur.iter().all(|s| s.is_none()) {
        return cfg;
    }

    // relabel label | Just (Jump target) <- shortcuts V.! fromLabel label
    //   = target | otherwise = label (Code.hs:355-357) — note it fires only
    //   when the SHORTCUT VALUE is itself a Jump (target block
    //   multi-instruction).
    let relabel = |label: Label| -> Label {
        match &cur[label.0 as usize] {
            Some(Insn::Jump(target)) => *target,
            _ => label,
        }
    };

    // CFG { cfgBlocks = V.imap (\i Block{..} -> Block { blockInsns =
    //   mapLabels relabel <$> inline i blockInsns }) cfgBlocks, cfgEntry =
    //   relabel cfgEntry } (Code.hs:334-340) — inline FIRST, then
    // mapLabels over the inlined stream.
    // PERF(port): the fixpoint clones Insn values per pass (O(n²) clones
    // worst case); the fast version threads shortcuts as indices into a
    // value table shared by passes.
    let cfg_blocks = cfg
        .cfg_blocks
        .iter()
        .enumerate()
        .map(|(i, block)| {
            let inlined = inline(i, &block.block_insns, &cur);
            let block_insns = inlined
                .iter()
                .map(|insn| map_labels(&relabel, insn))
                .collect();
            Block { block_insns }
        })
        .collect();
    CFG {
        cfg_blocks,
        cfg_entry: relabel(cfg.cfg_entry),
    }
}

/// The `inline` where-binding of shortcut (Code.hs:342-346).
fn inline(i: usize, block_insns: &[Insn], shortcuts: &[Option<Insn>]) -> Vec<Insn> {
    // inline i _ | Just insn <- shortcuts V.! i = [insn] (Code.hs:342-343)
    // — first clause wins regardless of the block's contents.
    if let Some(insn) = &shortcuts[i] {
        return vec![insn.clone()];
    }
    // inline _ (Jump target : insns) | Just insn <- shortcuts V.! fromLabel
    //   target = insn : insns (Code.hs:344-345) — blockInsns is REVERSED in
    // the source, so the Jump pattern is the block's LAST instruction; the
    // port's in-order Vec splits at the tail. The result splices the
    // target's shortcut instruction into the Jump's position.
    if let Some((rest, Insn::Jump(target))) = block_insns.split_last() {
        if let Some(insn) = &shortcuts[target.0 as usize] {
            let mut out = rest.to_vec();
            out.push(insn.clone());
            return out;
        }
    }
    // inline _ insns = insns (Code.hs:346)
    block_insns.to_vec()
}

