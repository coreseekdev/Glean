/// Frame segment which a register belongs to (source doc, Code.hs:437).
///
/// `data Segment = Input | Constant | Local` (Code.hs:438-439). The
/// derived-Enum CONSTRUCTOR ORDER is load-bearing: `fromEnum s` feeds the
/// 62-bit shift in [`register`] below (Input=0, Constant=1, Local=2 —
/// the encoded register layout the evaluator's frame expects).
// deriving(Eq,Ord,Enum,Bounded,Show) → derive(PartialEq, Eq, Debug) —
// the Ord/Enum/Bounded sides have no in-tree use beyond the packing
// arithmetic done explicitly below (RULE §2 disposition as rts/types.rs).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Segment {
    Input,
    Constant,
    Local,
}

// A register has a 'Segment' and an index within the segment, packed into
// a word. (Source comment, Code.hs:441-442.)

/// Create a register with the given `Segment` and index (source doc,
/// Code.hs:444).
///
/// `register :: Segment -> Word64 -> Register a` (Code.hs:445-446).
fn register<T: TyTag>(s: Segment, i: u64) -> Register<T> {
    // Register $ (fromIntegral (fromEnum s) `shiftL` 62) .|. i
    Register::new(((s as u64) << 62) | i)
}

/// Get the `Segment` of the register (source doc, Code.hs:448).
///
/// `registerSegment :: Register a -> Segment` (Code.hs:449-450) — the
/// typed view over the word-level decoder used by get_reg.
fn register_segment<T: TyTag>(r: Register<T>) -> Segment {
    register_segment_word(r.0)
}

fn register_segment_word(i: u64) -> Segment {
    // toEnum $ fromIntegral (i `shiftR` 62) — tags 0..2; tag 3 would be an
    // out-of-range toEnum under the derived Enum (an `error` whose exact
    // text is GHC-generated). Unreachable while registers are minted by
    // `register` with indices < 2^62 (a 2^62-register frame cannot exist).
    match i >> 62 {
        0 => Segment::Input,
        1 => Segment::Constant,
        2 => Segment::Local,
        _ => panic!("Segment.toEnum: out of range"),
    }
}

/// Get the index of the register within its segment (source doc,
/// Code.hs:452).
///
/// `registerIndex :: Register a -> Word64` (Code.hs:453-454).
fn register_index<T: TyTag>(r: Register<T>) -> u64 {
    register_index_word(r.0)
}

fn register_index_word(i: u64) -> u64 {
    i & 0x3FFF_FFFF_FFFF_FFFF // i .&. 0x3FFFFFFFFFFFFFFF
}

