    /// (Code.hs:185-188) — the callback arity is PINNED to one by the
    /// source signature, so no macro form is needed.
    pub fn output<A, F>(&mut self, f: F) -> A
    where
        F: FnOnce(Register<BinaryOutputPtr>, &mut Code) -> A,
    {
        // outputUninitialized $ \out -> do issue $ ResetOutput out; f out
        self.output_uninitialized(
            |sup| {
                let (out, next) = sup.supply();
                *sup = next;
                out
            },
            move |out, code| {
                code.issue(Insn::ResetOutput(out));
                f(out, code)
            },
        )
    }

    /// runLocal (Code.hs:190-205) — the shared skeleton of local and
    /// outputUninitialized. The two-phase register discipline is verbatim:
    /// (1) seed a supply at the CURRENT counter and pull the registers;
    /// (2) `set` the counter past them and `setmax` the high-water mark;
    /// (3) run the body (allocations inside it start above the reserved
    /// block); (4) restore the counter so the registers can be reused.
    fn run_local<SUP: Supply<RG>, RG, REGS, A>(
        &mut self,
        make: fn(RG) -> SUP,
        get: fn(&Code) -> RG,
        set: fn(&mut Code, RG),
        setmax: fn(&mut Code, RG),
        pull: impl FnOnce(&mut SUP) -> REGS,
        body: impl FnOnce(REGS, &mut Code) -> A,
    ) -> A {
        let r = get(self); // r <- Code $ S.gets get
        let mut sup = make(r); // S.runState (genCode cg) $ make r
        let regs = pull(&mut sup);
        let next = peek_supply(&sup); // !next = peekSupply sup
        set(self, next); // S.modify' $ setmax next . set next
        setmax(self, next); // (set before setmax, as in the composition)
        let x = body(regs, self); // x <- gen
        set(self, r); // Code $ S.modify' $ set r
        x
    }

