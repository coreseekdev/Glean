/// 'Pid' holds the glean Id corresponding to the definition of a
/// predicate.
///
/// As a Fid that Id points to the glean fact that holds the predicate
/// name and key type and value type).
///
/// Querying for this Id (as prefix of key) gives all facts for this
/// predicate. (Source doc, verbatim in substance.)
// Storable → repr(transparent) (deriving map); Enum/Prim/NFData → see
// deriving map. RULE §2 (numeric row): id newtype over the raw i64 —
// the Haskell wraps Int64 directly (Types.hs:51), NOT the thrift `Id`;
// that asymmetry (Pid: Int64, Fid: Id) is the source's and is preserved.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
#[repr(transparent)]
