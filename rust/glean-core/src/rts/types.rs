/// `data PidRef = PidRef Pid PredicateId deriving Show` (Types.hs:88-89).
/// Field names: the Haskell is positional; the port uses the crate's
/// named-field convention (cf. FieldDef_'s field_def_name/type) —
/// `pid` is the first component, `predicate_id` the second.
#[derive(Clone, Debug)]
pub struct PidRef {
    pub pid: Pid,
    pub predicate_id: PredicateId,
}

/// `instance Eq PidRef where PidRef a _ == PidRef b _ = a == b`
/// (Types.hs:91-92) — the PredicateId is IGNORED: two refs for the same
/// Pid are equal even if their predicate hashes differ. Not derived;
/// this ordering-of-precedence is exactly the source's.
impl PartialEq for PidRef {
    fn eq(&self, other: &Self) -> bool {
        self.pid == other.pid
    }
}

impl Eq for PidRef {}

/// `instance Ord PidRef where compare (PidRef a _) (PidRef b _) =
/// compare a b` (Types.hs:94-95) — pid only, consistent with Eq.
impl Ord for PidRef {
    fn cmp(&self, other: &Self) -> Ordering {
        self.pid.cmp(&other.pid)
    }
}

impl PartialOrd for PidRef {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

