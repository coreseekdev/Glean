/// Type describing the raw representation of a value. This makes
/// fewer distinctions than Type, in particular: there are no field
/// names or named types, and sugar like maybe, bool and enumerations
/// are expanded into their low-level representations.
/// (Source doc, verbatim.)
///
/// `data Rep id` (Types.hs:185-194) — stays generic: the id parameter
/// is used polymorphically in the tree (`hasRefs :: Rep a -> Bool`,
/// Traverse.hs:101). Box for the single-child arms, Vec for the list
/// arms — the source's strictness annotations are all lazy fields, so
/// owned boxes are the faithful strict-side rendering of sharing.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Rep<ID> {
    ByteRep,
    NatRep,
    ArrayRep(Box<Rep<ID>>),
    TupleRep(Vec<Rep<ID>>),
    SumRep(Vec<Rep<ID>>),
    SetRep(Box<Rep<ID>>),
    StringRep,
    PredicateRep(ID),
}

impl<ID> Rep<ID> {
    /// `deriving Functor` (Types.hs:194) — maps the id at every
    /// occurrence (nested through Array/Tuple/Sum/Set). Method form per
    /// the crate's bimap convention (angle/types.rs:1201): consuming
    /// self, `&mut` closure.
    pub fn map_id<R, F>(self, f: &mut F) -> Rep<R>
    where
        F: FnMut(ID) -> R,
    {
        match self {
            Rep::ByteRep => Rep::ByteRep,
            Rep::NatRep => Rep::NatRep,
            Rep::ArrayRep(t) => Rep::ArrayRep(Box::new(t.map_id(f))),
            Rep::TupleRep(ts) => Rep::TupleRep(ts.into_iter().map(|t| t.map_id(f)).collect()),
            Rep::SumRep(ts) => Rep::SumRep(ts.into_iter().map(|t| t.map_id(f)).collect()),
            Rep::SetRep(t) => Rep::SetRep(Box::new(t.map_id(f))),
            Rep::StringRep => Rep::StringRep,
            Rep::PredicateRep(id) => Rep::PredicateRep(f(id)),
        }
    }

    /// `deriving Foldable` (Types.hs:194) — folds the ids left-to-right
    /// in constructor/field order (same order map_id above traverses).
    /// Signature mirrors bifold_map's (angle/types.rs:1218): &self,
    /// accumulator + `&mut` visitor.
    pub fn fold_id<A, F>(&self, acc: &mut A, f: &mut F)
    where
        F: FnMut(&ID, &mut A),
    {
        match self {
            Rep::ByteRep | Rep::NatRep | Rep::StringRep => {}
            Rep::ArrayRep(t) | Rep::SetRep(t) => t.fold_id(acc, f),
            Rep::TupleRep(ts) | Rep::SumRep(ts) => {
                for t in ts {
                    t.fold_id(acc, f);
                }
            }
            Rep::PredicateRep(id) => f(id, acc),
        }
    }

    // TODO(port): `deriving Traversable` (Types.hs:194) has no port yet —
    // no canonical Rust trait for effectful traversal, and zero in-tree
    // consumers (grep over every Rep user: Traverse.hs/Typecheck.hs/
    // RTS.hs/Query/{Codegen,Opt,Reorder,Transform}/Write/JSON all recurse
    // explicitly or use none). If a consumer appears, add an effect-
    // parameterised traverse_id here (sequencing in the same order as
    // map_id/fold_id); do NOT silently subsume it under map_id — effects
    // order, and Functor does not subsume Traversable.
}

/// `instance Pretty id => Pretty (Rep id)` (Types.hs:196-204) — folded
/// into Display (header: Pretty vs Display); the id's own Display
/// renders the PredicateRep arm, exactly as `pretty id` did.
impl<ID: Display> Display for Rep<ID> {
    fn display(&self, opts: &DisplayOpts) -> Doc {
        match self {
            Rep::ByteRep => Doc::text("byte#"),
            Rep::NatRep => Doc::text("nat#"),
            Rep::ArrayRep(t) => Doc::text("[").append(t.display(opts)).append(Doc::text("]")),
            Rep::TupleRep(ts) => align(enclose_sep(
                Doc::text("("),
                Doc::text(")"),
                Doc::text(","),
                ts.iter().map(|t| t.display(opts)),
            )),
            Rep::SumRep(ts) => align(enclose_sep(
                Doc::text("(|"),
                Doc::text("|)"),
                Doc::text(","),
                ts.iter().map(|t| t.display(opts)),
            )),
            Rep::SetRep(t) => Doc::text("set ").append(t.display(opts)),
            Rep::StringRep => Doc::text("string#"),
            Rep::PredicateRep(id) => id.display(opts),
        }
    }
}

