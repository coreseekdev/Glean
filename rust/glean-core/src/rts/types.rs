/// Construct the representation of a Type (source doc).
///
/// `repType :: Type -> Rep Pid` (Types.hs:112-130). Takes the type by
/// shared reference and builds a fresh `Rep<Pid>` — the Haskell shares
/// the input while the output is always newly constructed (Pid is
/// unboxed), which `&Type -> Rep<Pid>` states directly.
pub fn rep_type(ty: &Type) -> Rep<Pid> {
    match ty {
        Type_::ByteTy => Rep::ByteRep,
        Type_::NatTy => Rep::NatRep,
        Type_::StringTy => Rep::StringRep,
        Type_::ArrayTy(t) => Rep::ArrayRep(Box::new(rep_type(t))),
        Type_::RecordTy(fields) => Rep::TupleRep(
            // [ repType ty | FieldDef _ ty <- fields ]
            fields
                .iter()
                .map(|f| rep_type(&f.field_def_type))
                .collect(),
        ),
        Type_::SumTy(fields) => Rep::SumRep(
            fields
                .iter()
                .map(|f| rep_type(&f.field_def_type))
                .collect(),
        ),
        Type_::SetTy(t) => Rep::SetRep(Box::new(rep_type(t))),
        Type_::PredicateTy(_, PidRef { pid, .. }) => Rep::PredicateRep(*pid),
        Type_::NamedTy(_, expanded) => rep_type(&expanded.expanded_type_type),
        // RULE §2 (A8, pattern-shape): the source routes these three
        // arms through the Schema.Util lowerers (`repType (lowerMaybe
        // ty)` etc., Types.hs:124-126); the port CALLS lower_maybe/
        // lower_enum/lower_bool rather than inlining the lowered sum
        // shape — same discipline as the source's SetTy-shape ruling.
        // PERF(port): the by-value lowerers force one subtree clone per
        // maybe/enum level; the fast version is a borrow-based structural
        // walk that compares against the would-be SumTy without
        // materialising it.
        Type_::MaybeTy(t) => rep_type(&lower_maybe((**t).clone())),
        Type_::EnumeratedTy(names) => rep_type(&lower_enum(names)),
        Type_::BooleanTy => rep_type(&lower_bool()),
        // RULE §2 (partial-functions row): the source `error`s here;
        // panic with the SAME message, byte for byte.
        Type_::TyVar(_) => panic!("repType: TyVar"),
        Type_::HasTy(..) => panic!("repType: HasTy"),
        Type_::HasKey(..) => panic!("repType: HasKey"),
        Type_::ElementsOf(..) => panic!("repType: ElementsOf"),
    }
}

/// `sumLike :: Type -> Maybe [Glean.RTS.Types.FieldDef]`
/// (Types.hs:132-137). By-ref in, owned fields out: the Haskell returns
/// (a function of) fields out of the shared input; the port clones the
/// SumTy fields and lets the lowerers build the derived ones.
pub fn sum_like(ty: &Type) -> Option<Vec<FieldDef>> {
    match ty {
        Type_::SumTy(fields) => Some(fields.clone()),
        Type_::MaybeTy(t) => Some(maybe_fields((**t).clone())),
        Type_::EnumeratedTy(names) => Some(enum_fields(names)),
        Type_::BooleanTy => Some(bool_fields()),
        _ => None,
    }
}

/// Compare types for (structural) equality (source doc).
///
/// `eqType :: AngleVersion -> Type -> Type -> Bool` (Types.hs:140-174).
/// Arm ORDER is load-bearing: the Haskell case rows fire top to bottom,
/// so the NamedTy/MaybeTy/EnumeratedTy/BooleanTy half-rows (one side a
/// wildcard) must stay in exactly this sequence — e.g. `(MaybeTy t,
/// NamedTy _)` hits the right-NamedTy row BEFORE any MaybeTy row, which
/// re-dispatches through the dereferenced right operand. AngleVersion is
/// Copy; passed by value as the source passes it (unboxed newtype).
pub fn eq_type(version: AngleVersion, a: &Type, b: &Type) -> bool {
    match (a, b) {
        (Type_::ByteTy, Type_::ByteTy) => true,
        (Type_::NatTy, Type_::NatTy) => true,
        (Type_::StringTy, Type_::StringTy) => true,
        (Type_::ArrayTy(x), Type_::ArrayTy(y)) => eq_type(version, x, y),
        (Type_::RecordTy(as_), Type_::RecordTy(bs)) => {
            // isTuple = all (Text.isInfixOf "tuplefield" . fieldDefName)
            let is_tuple =
                |fields: &[FieldDef]| fields.iter().all(|f| f.field_def_name.contains("tuplefield"));
            // previous to version 7 records were always compared
            // structurally
            let compare_structurally =
                version < AngleVersion(7) || is_tuple(as_) || is_tuple(bs);
            // structural equality for tuples by ignoring field names.
            // eqField fa fb = fa == fb  (field NAMES)
            as_.len() == bs.len()
                && as_.iter().zip(bs).all(|(fa, fb)| {
                    eq_type(version, &fa.field_def_type, &fb.field_def_type)
                        && (compare_structurally || fa.field_def_name == fb.field_def_name)
                })
        }
        (Type_::SumTy(as_), Type_::SumTy(bs)) => {
            as_.len() == bs.len()
                && as_
                    .iter()
                    .zip(bs)
                    .all(|(fa, fb)| eq_type(version, &fa.field_def_type, &fb.field_def_type))
        }
        // PidRef's Eq is pid-only (above), so this row already compares
        // pids only, as the source's `p == q` does via that instance.
        (Type_::PredicateTy(_, PidRef { pid: p, .. }), Type_::PredicateTy(_, PidRef { pid: q, .. })) => {
            p == q
        }
        // n == m is TypeId's Eq — hash-only (angle/types.rs:591-598),
        // the source's semantics via its derived instance.
        (Type_::NamedTy(_, x), Type_::NamedTy(_, y)) => {
            x.expanded_type_ref == y.expanded_type_ref
                || eq_type(
                    version,
                    &x.expanded_type_type,
                    &y.expanded_type_type,
                )
        }
        (Type_::NamedTy(_, x), u) => eq_type(version, &x.expanded_type_type, u),
        (t, Type_::NamedTy(_, y)) => eq_type(version, t, &y.expanded_type_type),
        // RULE §2 (A8) + PERF(port): the half-rows below re-dispatch
        // through lower_maybe/lower_enum/lower_bool exactly as the
        // source does (Types.hs:166-173); the clones are the by-value
        // lowerer tax — fast version: compare against the would-be
        // SumTy without materialising it.
        (Type_::MaybeTy(x), Type_::MaybeTy(y)) => eq_type(version, x, y),
        (Type_::MaybeTy(x), u) => eq_type(version, &lower_maybe((**x).clone()), u),
        (t, Type_::MaybeTy(y)) => eq_type(version, t, &lower_maybe((**y).clone())),
        (Type_::EnumeratedTy(xs), Type_::EnumeratedTy(ys)) => xs == ys,
        (Type_::EnumeratedTy(xs), t) => eq_type(version, &lower_enum(xs), t),
        (t, Type_::EnumeratedTy(xs)) => eq_type(version, t, &lower_enum(xs)),
        (Type_::BooleanTy, Type_::BooleanTy) => true,
        (Type_::BooleanTy, t) => eq_type(version, &lower_bool(), t),
        (t, Type_::BooleanTy) => eq_type(version, t, &lower_bool()),
        _ => false,
    }
}

/// dereference NamedTy on the outside of a Type (source doc).
///
/// `derefType :: Type -> Type` (Types.hs:177-179). The Haskell returns
/// the SAME (shared) value in the fallthrough case — `&Type -> &Type`
/// is the sharing-preserving translation, no clone.
pub fn deref_type(ty: &Type) -> &Type {
    match ty {
        Type_::NamedTy(_, expanded) => deref_type(&expanded.expanded_type_type),
        other => other,
    }
}

