/// `marshalPredicateStats
///   :: (Ptr CSize -> Ptr (Ptr Int64) -> Ptr (Ptr Word64)
///       -> Ptr (Ptr Word64) -> IO CString)
///   -> IO [(Pid, PredicateStats)]` (Stats.hs:27-43).
///
/// Runs the getter through [`invoke`], then reads its three malloc'd
/// arrays under nested `using_malloced` brackets — indices `0 .. count` in
/// array order (the C++ DenseMap order `marshal` wrote), `Pid pid` from
/// the i64 ids and both `PredicateStats` fields via the source's
/// `fromIntegral` (Word64 -> Int64: `as` is the same two's-complement
/// reinterpretation, kept bug-for-bug for counts above i64::MAX).
pub fn marshal_predicate_stats(
    get: impl FnOnce(*mut usize, *mut *mut i64, *mut *mut u64, *mut *mut u64) -> *const c_char,
) -> Result<Vec<(Pid, PredicateStats)>, FfiError> {
    let mut count: usize = 0;
    let mut pids: *mut i64 = ptr::null_mut();
    let mut counts: *mut u64 = ptr::null_mut();
    let mut sizes: *mut u64 = ptr::null_mut();

    // SAFETY: `get` is the caller's getter — for the one in-tree consumer,
    // `glean_factset_predicateStats`, whose C contract (ffi.h:277-282) is
    // exactly to write the filled count and three freshly-malloc'd arrays
    // through these four out-params; all four are initialised stack locals,
    // and invoke owns the error string's release.
    unsafe { invoke(|| get(&mut count, &mut pids, &mut counts, &mut sizes)) }?;

    // The read pass, a plain closure handed to the innermost bracket:
    // the Haskell's `forM [0 .. fromIntegral count - 1]` (Stats.hs:39).
    // NOTE the source SHADOWS `count` inside the loop with the element
    // value (Stats.hs:41-42) — preserved here.
    let read_all = || {
        let mut out = Vec::with_capacity(count);
        for i in 0..count {
            // SAFETY: `pids` is the malloc'd i64 array of `count` elements
            // the C++ marshal released to the caller (stats.cpp:30/:36/
            // :43), and `i < count`, so this element is in bounds.
            let pid = unsafe { *pids.add(i) };
            // SAFETY: as above, for the uint64_t counts array
            // (stats.cpp:31/:37/:44); the source's shadowing name.
            let count = unsafe { *counts.add(i) };
            // SAFETY: as above, for the uint64_t sizes array
            // (stats.cpp:32/:38/:45); the source's name.
            let size = unsafe { *sizes.add(i) };
            out.push((
                Pid(pid),
                PredicateStats {
                    count: count as i64,
                    size: size as i64,
                },
            ));
        }
        out
    };

    // Each using_malloced frees one array on every exit path; the nesting
    // order is the source's (`usingMalloced pids $ usingMalloced counts $
    // usingMalloced sizes $ ...`, Stats.hs:36-38), so the guards unwind
    // sizes-first.
    // SAFETY: the three pointers are the malloc'd arrays `get` just
    // transferred ownership of (possibly null when count == 0 — libc::free
    // accepts null, and the read loop never dereferences); they are not
    // retained anywhere else, and using_malloced is exactly the source's
    // `finally`-style bracket.
    let stats = unsafe {
        using_malloced(pids.cast::<c_void>(), || {
            using_malloced(counts.cast::<c_void>(), || {
                using_malloced(sizes.cast::<c_void>(), read_all)
            })
        })
    };
    Ok(stats)
}

