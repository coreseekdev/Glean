// Re-expressed tests for the unit glean/angle/Glean/Angle/Hash.hs
// (rust/glean-angle/src/angle/hash.rs), per RULE §4: Haskell tests are not
// translated; each crate's tests/ holds the re-expression cases, and the
// judge (migration/judge/) is the real referee.
//
// Every test goes through the unit's PUBLIC API only — fingerprint_data,
// hash0, hash_string, hash_byte_string, Fingerprint. The unit's private
// MD5 internals (md5_digest, the Md5 struct) are covered implicitly: the
// one-shot public calls exercise exactly the buffering paths the shipped
// API uses (partial-block top-up happens on every padding pass; the RFC
// 80-digit vector and the boundary-length suite below drive the
// multi-block path).
//
// Every expected value below is either an RFC 1321 reference vector, a
// GHC-computed constant lifted from Glean's own sources, or a digest
// computed offline with CPython's hashlib (an independent implementation)
// — none were generated by this crate's implementation.

use glean_angle::angle::hash::{
    fingerprint_data, hash0, hash_byte_string, hash_string, Fingerprint,
};

/// RFC 1321 §A.5 reference suite, each digest re-expressed as the two
/// big-endian u64 words that fingerprint_data must produce.
#[test]
fn md5_rfc1321_vectors_through_fingerprint_data() {
    let cases: &[(&[u8], u64, u64)] = &[
        // "" -> d41d8cd98f00b204e9800998ecf8427e
        (b"", 0xd41d_8cd9_8f00_b204, 0xe980_0998_ecf8_427e),
        // "a" -> 0cc175b9c0f1b6a831c399e269772661
        (b"a", 0x0cc1_75b9_c0f1_b6a8, 0x31c3_99e2_6977_2661),
        // "abc" -> 900150983cd24fb0d6963f7d28e17f72
        (b"abc", 0x9001_5098_3cd2_4fb0, 0xd696_3f7d_28e1_7f72),
        // "message digest" -> f96b697d7cb7938d525a2f31aaf161d0
        (
            b"message digest",
            0xf96b_697d_7cb7_938d,
            0x525a_2f31_aaf1_61d0,
        ),
        // "abcdefghijklmnopqrstuvwxyz" -> c3fcd3d76192e4007dfb496cca67e13b
        (
            b"abcdefghijklmnopqrstuvwxyz",
            0xc3fc_d3d7_6192_e400,
            0x7dfb_496c_ca67_e13b,
        ),
        // "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
        // -> d174ab98d277d9f5a5611c2c9f419d9f
        (
            b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789",
            0xd174_ab98_d277_d9f5,
            0xa561_1c2c_9f41_9d9f,
        ),
        // "1234567890" x 8 (80 digits) -> 57edf4a22be3c955ac49da2e2107b67a;
        // the only RFC vector >= 64 bytes, i.e. the multi-block case
        (
            b"12345678901234567890123456789012345678901234567890123456789012345678901234567890",
            0x57ed_f4a2_2be3_c955,
            0xac49_da2e_2107_b67a,
        ),
    ];
    for (input, w1, w2) in cases {
        assert_eq!(
            fingerprint_data(input),
            Fingerprint::new(*w1, *w2),
            "fingerprint_data({:?})",
            String::from_utf8_lossy(input)
        );
    }
}

/// The GHC-pinned layout vector, derived from
/// glean/test/tests/TestShard.hs (`dbShard (Repo "test" "1234")` ==
/// "6825422262439797754" where dbShardWord = fingerprint1 >> 1 over the
/// bytes "test/1234"). This single vector proves both the MD5 core and
/// the big-endian two-word Fingerprint split against a real
/// GHC.Fingerprint result.
#[test]
fn fingerprint_layout_pinned_by_testshard() {
    let fp = fingerprint_data(b"test/1234");
    assert_eq!(fp.fingerprint1, 0xbd71_8ac5_2588_c7f5);
    assert_eq!(fp.fingerprint2, 0x291e_839f_03ed_457c);
    assert_eq!(fp.fingerprint1 >> 1, 6825422262439797754u64);
}

/// GHC.Fingerprint.Type's Show: `show (Fingerprint w1 w2) =
/// hex16 w1 ++ hex16 w2` — 32 lowercase hex digits, each word zero-padded
/// to 16 digits, no constructor tag, no 0x, no space. This is a persisted
/// surface (ComputeIds.hs:307 embeds it in stored SchemaIds). Vector: the
/// TestShard bytes "test/1234" (MD5 bd718ac52588c7f5291e839f03ed457c).
#[test]
fn fingerprint_display_is_ghc_show_hex16() {
    let fp = fingerprint_data(b"test/1234");
    assert_eq!(format!("{}", fp), "bd718ac52588c7f5291e839f03ed457c");
    // hex16 zero-pads: both words must render as exactly 16 digits
    // (derived from the quoted Show definition, not from this impl)
    assert_eq!(
        format!("{}", Fingerprint::new(0, 1)),
        "00000000000000000000000000000001"
    );
}

/// hash_string must reproduce GHC's fingerprintString marshalling: each
/// Char as its BIG-ENDIAN 32-bit code point — 4 bytes per character,
/// NOT UTF-8 (GHC.Fingerprint.hs:57-63). For "abc" the hashed bytes are
/// 00 00 00 61 | 00 00 00 62 | 00 00 00 63; the expected Fingerprint
/// was recomputed offline with an independent MD5 and cross-checked in
/// review: 0x2fd3677608927527 0x1be2a71ed2c95d2b.
#[test]
fn hash_string_matches_ghc_fingerprint_string() {
    let expected = Fingerprint::new(0x2fd3_6776_0892_7527, 0x1be2_a71e_d2c9_5d2b);
    assert_eq!(hash_string("abc"), expected);
    assert_eq!(
        hash_byte_string(&[0, 0, 0, 0x61, 0, 0, 0, 0x62, 0, 0, 0, 0x63]),
        expected
    );
    // GHC never produces UTF-8 agreement for non-empty strings
    // (MD5("abc") = 90015098... != 2fd36776...)
    assert_ne!(hash_string("abc"), hash_byte_string(b"abc"));
    // a non-ASCII char discriminates the encodings directly: U+00E9
    // marshals as 00 00 00 E9 (a single E9 byte in UTF-8)
    assert_eq!(hash_string("\u{e9}"), hash_byte_string(&[0, 0, 0, 0xE9]));
}

/// Block and padding boundaries through the one-shot public API:
/// lengths 55/56/57 bracket the padding-fits-one-block vs spills-into-two
/// split; 63/64/65 the last-block edge; 127/128/129 multi-block tails;
/// 255/256 full cycles. Expected values computed offline with CPython's
/// hashlib (independent implementation) over the same input pattern as
/// the port's original incremental test (bytes 0u8..=255 cycling).
#[test]
fn hash_byte_string_covers_block_and_padding_boundaries() {
    let cases: &[(usize, u64, u64)] = &[
        (55, 0x6912_ee65_fff2_d9f9, 0xce25_08cd_df8b_cda0),
        (56, 0x51fd_d1ac_da72_405d, 0xfdfa_03fc_b858_96d7),
        (57, 0x5320_ef4c_17ef_34a0, 0xcf2d_b763_338d_25eb),
        (63, 0x48a6_2952_2190_8e8e, 0x0938_f773_a718_5e72),
        (64, 0xb2d3_f56b_c197_fd98, 0x5d59_6507_9b5e_7148),
        (65, 0x8bd7_0538_01c7_6842, 0x0faf_816f_adba_971c),
        (127, 0x8402_b21e_7bc7_9064, 0x93ba_e0da_c017_1f9),
        (128, 0x37ef_f018_66ba_3f53, 0x8421_b30b_7cbe_fcac),
        (129, 0x46f9_8669_2847_558f, 0xc38b_0cec_e591_c20f),
        (255, 0x11b7_aaa6_4c41_3d2f, 0x0fcc_f893_881c_46a2),
        (256, 0xe2c8_65db_4162_bed9, 0x63bf_aa9e_f6ac_18f0),
    ];
    for (len, w1, w2) in cases {
        let input: Vec<u8> = (0u8..=255).cycle().take(*len).collect();
        assert_eq!(
            hash_byte_string(&input),
            Fingerprint::new(*w1, *w2),
            "hash_byte_string(len={})",
            len
        );
    }
}

#[test]
fn hash0_is_zero_fingerprint() {
    assert_eq!(hash0(), Fingerprint::new(0, 0));
}
